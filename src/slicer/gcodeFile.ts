/**
 * Reading a G-code file someone made elsewhere (Orca, LightBurn, Fusion, or an
 * earlier Studio file), so Job setup can show it and check it before sending.
 *
 *   readJobFile   which toolhead it says it's for, which program made it, the
 *                 program's own time and filament figures, and its toolpath
 *                 (the moves that print or cut) for the bed view
 */
import { toolheadFromGcode } from '@/moonraker/gcodeHeader'

export const GCODE_TYPES = ['gcode', 'gco', 'g', 'nc', 'ngc'] as const

export interface JobFileInfo {
  toolhead: string | null
  /** e.g. "OrcaSlicer 2.4.2", "Rhino Studio 0.5.0" */
  madeBy: string | null
  seconds: number | null
  filamentMm: number | null
  /** XY polylines of the working moves (printing or cutting), thinned for drawing */
  paths: Array<Array<[number, number]>>
  bounds: { min: [number, number]; max: [number, number] } | null
  lines: number
}

/** "1d 2h 3m 4s" / "38m 6s" -> seconds */
export function durationOf(s: string): number | null {
  let t = 0
  let any = false
  for (const [, n, u] of s.matchAll(/(\d+(?:\.\d+)?)\s*([dhms])/g)) {
    any = true
    t += +n! * ({ d: 86400, h: 3600, m: 60, s: 1 } as Record<string, number>)[u!]!
  }
  return any ? t : null
}

export function readJobFile(text: string, maxPoints = 40000): JobFileInfo {
  const madeBy =
    /^;\s*generated by\s+([A-Za-z][\w.\- ]*?\d[\w.\-]*)/im.exec(text)?.[1]?.trim() ??
    /^;\s*Made by (Rhino Studio [\w.\-]+)/m.exec(text)?.[1] ??
    /^;\s*Generated (?:by|with) ([^\n;]+)/im.exec(text)?.[1]?.trim() ??
    (/LightBurn/i.test(text.slice(0, 4000)) ? 'LightBurn' : null)
  const est = /^;\s*estimated printing time[^=\n]*=\s*([^\n]+)$/im.exec(text)?.[1]
  const studioTime = /print time: (\d+)s/.exec(text)?.[1]
  const fil = /^;\s*filament used \[mm\]\s*=\s*([\d.]+)/im.exec(text)?.[1] ?? /filament used: ([\d.]+) mm/.exec(text)?.[1]

  // Toolpath: absolute XY of moves that print (E > 0) or cut (G1 with a tool on / any G1-G3 when no E is used)
  const usesE = /^G1\b[^;\n]*\bE\d*\.?\d/m.test(text)
  const raw = text.split(/\r?\n/)
  const paths: Array<Array<[number, number]>> = []
  let cur: Array<[number, number]> | null = null
  let x: number | null = null
  let y: number | null = null
  let abs = true
  let total = 0
  const min: [number, number] = [Infinity, Infinity]
  const max: [number, number] = [-Infinity, -Infinity]
  const num = (l: string, w: string) => {
    const m = new RegExp(`\\b${w}(-?\\d*\\.?\\d+)`).exec(l)
    return m ? +m[1]! : null
  }
  for (const rl of raw) {
    const l = rl.replace(/;.*$/, '').trim()
    if (!l) continue
    const c = l.split(/\s+/)[0]!.toUpperCase()
    if (c === 'G90') abs = true
    else if (c === 'G91') abs = false
    else if (/^G[0-3]$/.test(c) && abs) {
      const nx: number | null = num(l, 'X') ?? x
      const ny: number | null = num(l, 'Y') ?? y
      const e = num(l, 'E')
      const working = c !== 'G0' && (usesE ? (e ?? 0) > 0 : true)
      if (nx !== null && ny !== null && (nx !== x || ny !== y)) {
        if (working && x !== null && y !== null) {
          if (!cur) {
            cur = [[x, y]]
            paths.push(cur)
          }
          cur.push([nx, ny])
          total++
          min[0] = Math.min(min[0], x, nx)
          min[1] = Math.min(min[1], y, ny)
          max[0] = Math.max(max[0], x, nx)
          max[1] = Math.max(max[1], y, ny)
        } else cur = null
      }
      x = nx
      y = ny
    }
  }
  // Thin evenly so a big print stays quick to draw
  const keep = Math.max(1, Math.ceil(total / maxPoints))
  const thin = keep === 1 ? paths : paths.filter((_, i) => i % keep === 0)
  return {
    toolhead: toolheadFromGcode(text),
    madeBy,
    seconds: est ? durationOf(est) : studioTime ? +studioTime : null,
    filamentMm: fil ? +fil : null,
    paths: thin,
    bounds: Number.isFinite(min[0]) ? { min, max } : null,
    lines: raw.length,
  }
}

/**
 * The copy of an uploaded file that goes to the Rhino. A file without a
 * `; rhino_toolhead` line or `START_JOB TOOLHEAD=` (what Files reads, see
 * moonraker/gcodeHeader.ts) gets the line for the toolhead the user confirmed,
 * so Files can match it to the mounted tool before it starts. Nothing else changes.
 */
export function withToolhead(text: string, toolhead: string): string {
  if (toolheadFromGcode(text)) return text
  return `; rhino_toolhead = ${toolhead}\n; (toolhead line added by Rhino Studio)\n${text}`
}
