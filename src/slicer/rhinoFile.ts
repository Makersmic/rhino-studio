/**
 * Turns Kiri:Moto's output into a Rhino job file.
 *
 * Every file starts with the same header block, which Studio's Files screen and
 * the machine both read:
 *
 *   ; rhino_toolhead = BlockOne          (src/moonraker/gcodeHeader.ts)
 *
 * and then, per process:
 *
 *   fdm        M140 S0, M104 S0, then START_JOB TOOLHEAD= MATERIAL= NOZZLE_SIZE= EXTRUDER=
 *              (the same line as the OrcaSlicer profile: it checks the mounted tool,
 *              homes, heats from the material table and primes), G90 G21 M83 G92 E0,
 *              the print, END_PRINT.
 *   laser      G21 G90 M5, the cut (M3 S<power> ... M5, repeated for each pass),
 *              M5, DEACTIVATE_LASER, END_PRINT. No Z moves: it cuts at the focus
 *              LASER_JOB_SETUP sets. The file never switches the laser's rail on
 *              (_LASER_START does that), so run on its own it can't fire.
 *   dragknife  G21 G90, the cut (Z0 = the surface SET_Z_ZERO sets), END_PRINT.
 *              Blade plunges are slowed to the plunge feed.
 *   cnc        G21 G90, the toolpath in work coordinates, M5, END_PRINT. The spindle
 *              is started and stopped by CNC_JOB_SETUP / M5, not by this file.
 */
import type { MachineInfo, PartInfo, PrepareJob } from './types'

export const STUDIO_FILE_VERSION = 1

export interface RhinoFile {
  text: string
  name: string
  /** where the cut or print actually lands, after placement (machine or work coordinates) */
  bounds: { min: [number, number, number]; max: [number, number, number] } | null
}

const fmt = (v: number) => {
  const s = v.toFixed(3)
  return s.replace(/\.?0+$/, '') || '0'
}

/** Safe for FILE= on the setup wizards: letters, digits, - _ . only. */
export function fileName(partName: string, job: PrepareJob): string {
  const base = partName.replace(/\.[^.]+$/, '').replace(/[^A-Za-z0-9_-]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 40) || 'part'
  const mat = job.material.replace(/[^A-Za-z0-9_-]+/g, '_')
  return `${base}-${job.toolhead}${mat ? `-${mat}` : ''}.gcode`
}

function header(job: PrepareJob, part: PartInfo, studioVersion: string): string[] {
  const lines = [
    `; Made by Rhino Studio ${studioVersion} with the Kiri:Moto engine`,
    `; rhino_toolhead = ${job.toolhead}`,
    `; rhino_process = ${job.process}`,
    `; rhino_material = ${job.material}`,
    `; rhino_part = ${part.name.replace(/[\r\n]/g, ' ')} (${fmt(part.size.x)} x ${fmt(part.size.y)} x ${fmt(part.size.z)} mm)`,
    `; rhino_studio_file = ${STUDIO_FILE_VERSION}`,
    `; rhino_settings = ${JSON.stringify(settingsFor(job))}`,
  ]
  if (job.process === 'laser') lines.push('; Start with LASER_JOB_SETUP FILE=<this file> (Studio: Files > Start). It sets the focus and test-fires first.')
  if (job.process === 'dragknife') lines.push('; Start with DRAGKNIFE_JOB_SETUP FILE=<this file> (Studio: Files > Start). Z0 is the material surface.')
  if (job.process === 'cnc') lines.push('; Start with CNC_JOB_SETUP FILE=<this file> (Studio: Files > Start). X0 Y0 = stock front-left corner, Z0 = stock top.')
  return lines
}

function settingsFor(job: PrepareJob) {
  switch (job.process) {
    case 'fdm':
      return job.fdm
    case 'laser':
      return job.laser
    case 'dragknife':
      return job.knife
    case 'cnc':
      return job.cnc
  }
}

/** Kiri lines we keep: moves, fan, dwell, laser on/off, comments. Its own header comments are dropped. */
function body(kiri: string): string[] {
  return kiri
    .split(/\r?\n/)
    .map((l) => l.trimEnd())
    .filter((l) => l !== '' && !/^; (Generated by Kiri|[A-Z][a-z]{2} [A-Z][a-z]{2} \d|Bed |Target|Stock |--- process|[a-zA-Z]+ = )/.test(l))
}

interface XY {
  x: number
  y: number
}

/** Bounds of X/Y over every G0/G1/G2/G3 that gives them (absolute moves only, which Kiri writes). */
export function xyBounds(lines: string[]): { min: XY; max: XY } | null {
  let min: XY = { x: Infinity, y: Infinity }
  let max: XY = { x: -Infinity, y: -Infinity }
  for (const l of lines) {
    if (!/^G[0-3]\b/.test(l)) continue
    const x = /\bX(-?\d*\.?\d+)/.exec(l)
    const y = /\bY(-?\d*\.?\d+)/.exec(l)
    if (x) {
      min.x = Math.min(min.x, +x[1]!)
      max.x = Math.max(max.x, +x[1]!)
    }
    if (y) {
      min.y = Math.min(min.y, +y[1]!)
      max.y = Math.max(max.y, +y[1]!)
    }
  }
  return Number.isFinite(min.x) && Number.isFinite(min.y) ? { min, max } : null
}

/** Move every X/Y by (dx, dy). Only for absolute G0/G1 lines (laser and knife output). */
export function shiftXY(lines: string[], dx: number, dy: number): string[] {
  return lines.map((l) => {
    if (!/^G[01]\b/.test(l)) return l
    return l.replace(/\b([XY])(-?\d*\.?\d+)/g, (_m, ax: string, v: string) => `${ax}${fmt(+v + (ax === 'X' ? dx : dy))}`)
  })
}

export function rhinoFile(kiri: string, job: PrepareJob, part: PartInfo, _machine: MachineInfo, studioVersion: string): RhinoFile {
  const head = header(job, part, studioVersion)
  let cut = body(kiri)
  const out: string[] = [...head, '']

  if (job.process === 'laser' || job.process === 'dragknife') {
    // Kiri wrote the cut from its lower-left corner; centre it where the part sits on the bed.
    const b = xyBounds(cut)
    if (b) {
      const dx = job.placement.x - (b.min.x + b.max.x) / 2
      const dy = job.placement.y - (b.min.y + b.max.y) / 2
      cut = shiftXY(cut, dx, dy)
    }
  }

  switch (job.process) {
    case 'fdm': {
      const f = job.fdm
      const mat = materialParam(job.material)
      out.push(
        'M140 S0 ; bed off until START_JOB heats it from the material table',
        'M104 S0 ; nozzle off until START_JOB heats it',
        `START_JOB TOOLHEAD=${job.toolhead} MATERIAL=${mat} NOZZLE_SIZE=${fmt(f.nozzle)} EXTRUDER=${f.path}`,
        'G90 ; absolute X/Y/Z',
        'G21 ; millimetres',
        'M83 ; relative extrusion (Kiri:Moto writes E per move)',
        'G92 E0',
        ...cut,
        'M107 ; part fan off',
        'END_PRINT',
      )
      break
    }
    case 'laser': {
      const passes = Math.max(1, Math.round(job.laser.passes))
      out.push('G21 ; millimetres', 'G90 ; absolute machine X/Y, same as the Studio bed', 'M5 ; laser off before the first move')
      for (let p = 1; p <= passes; p++) {
        if (passes > 1) out.push(`; pass ${p} of ${passes}`)
        out.push(...cut)
      }
      out.push('M5 ; laser off', 'DEACTIVATE_LASER ; laser power rail off', 'END_PRINT')
      break
    }
    case 'dragknife': {
      const plunge = Math.max(10, job.knife.plunge)
      out.push('G21 ; millimetres', 'G90 ; absolute machine X/Y; Z0 = material surface')
      for (const l of cut) {
        // Kiri drops the blade with a rapid; go in at the plunge feed instead
        const down = /^G0 Z(-\d*\.?\d+)\s*$/.exec(l)
        out.push(down ? `G1 Z${down[1]} F${fmt(plunge)}` : l)
      }
      out.push('G0 Z5 ; blade up', 'END_PRINT')
      break
    }
    case 'cnc': {
      out.push('G21 ; millimetres', 'G90 ; absolute work coordinates (CNC_JOB_SETUP sets X0 Y0 and Z0)', ...cut, 'M5 ; spindle off', 'END_PRINT')
      break
    }
  }

  const b = xyBounds(out.filter((l) => !l.startsWith(';')))
  const z = zRange(out)
  return {
    text: out.join('\n') + '\n',
    name: fileName(part.name, job),
    bounds: b ? { min: [b.min.x, b.min.y, z.min], max: [b.max.x, b.max.y, z.max] } : null,
  }
}

/** PLA_0_4 -> PLA (START_JOB rebuilds the key from MATERIAL, NOZZLE_SIZE and EXTRUDER). */
function materialParam(key: string): string {
  const m = /^(.+?)_\d+_\d+(?:_T\d)?$/.exec(key)
  return (m ? m[1]! : key).replace(/[^A-Za-z0-9_]/g, '')
}

function zRange(lines: string[]): { min: number; max: number } {
  let min = Infinity
  let max = -Infinity
  for (const l of lines) {
    if (!/^G[0-3]\b/.test(l)) continue
    const z = /\bZ(-?\d*\.?\d+)/.exec(l)
    if (z) {
      min = Math.min(min, +z[1]!)
      max = Math.max(max, +z[1]!)
    }
  }
  return Number.isFinite(min) ? { min, max } : { min: 0, max: 0 }
}
