import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { DEFAULT_MACHINE } from '@/slicer/types'
import { newJob, type Material } from '@/slicer/profiles'
import { partInfo } from '@/slicer/model'
import { drawingBox, laserLoops, loopRef } from '@/slicer/laserOps'
import { newChain, type Chain, type LaserWork } from './chain'
import { place, type Body } from './design'
import { buildJobs, groupOf, type Slicer } from './build'

const box = (x0: number, y0: number, z0: number, x1: number, y1: number, z1: number) => {
  const p = [[x0, y0, z0], [x1, y0, z0], [x1, y1, z0], [x0, y1, z0], [x0, y0, z1], [x1, y0, z1], [x1, y1, z1], [x0, y1, z1]]
  const f = [[0, 1, 2], [0, 2, 3], [4, 6, 5], [4, 7, 6], [0, 5, 1], [0, 4, 5], [1, 6, 2], [1, 5, 6], [2, 7, 3], [2, 6, 7], [3, 4, 0], [3, 7, 4]]
  return new Float32Array(f.flatMap((t) => t.flatMap((i) => p[i]!)))
}
const PLA: Material = { key: 'PLA_0_4', name: 'PLA', nozzle: 0.4, extruderTemp: 210, bedTemp: 60, fan: 1, feed: 50 }
const tools = { print: 'BlockOne', laser: 'LightSaber' }
const CUT = readFileSync(new URL('../slicer/fixtures/kiri-laser-nested.gcode', import.meta.url), 'utf8')

/** a stand-in for Kiri: one square of printing at the part's place, tagged so a test can tell which group it was */
const calls: Array<{ x: number; y: number; w: number }> = []
const slicer: Slicer = {
  async fdm(_v, job, part) {
    calls.push({ x: job.placement.x, y: job.placement.y, w: part.size.x })
    const [x, y] = [job.placement.x, job.placement.y]
    return `; Generated by Kiri:Moto\nG0 X${x} Y${y} Z0.2 F6000\nG1 X${x + 5} Y${y} E0.4 F1200\nG1 X${x + 5} Y${y + 5} E0.4\n`
  },
  async laser(file, _job) {
    return { kiri: CUT, part: partInfo(file.name, box(0, 0, 0, 60, 40, 1), true) }
  },
}

const body = (id: number, name: string, role: Body['role'], x0: number, y0: number, x1: number, y1: number, h = 2): Body => ({ id, name, role, vertices: box(x0, y0, 0, x1, y1, h) })
const bodies = [body(1, 'sheet', 'sheet', 0, 0, 100, 60, 3), body(2, 'jig', 'fixture', -12, 0, -2, 60, 4), body(3, 'logo', 'feature', 35, 20, 65, 40, 2)]

function chain(over: Partial<Chain> = {}): Chain {
  const c = newChain('Front plate 001', 'sheet-print-laser', tools)
  c.thickness = 3
  c.sheet = { width: 100, depth: 60, x: 150, y: 150 }
  return { ...c, ...over }
}
const LOOPS = laserLoops(CUT.split('\n').filter(Boolean))
const SQUARE = loopRef(LOOPS.find((l) => Math.abs(l.box.x1 - l.box.x0 - 15) < 0.5 && Math.abs(l.box.y1 - l.box.y0 - 16) < 0.5)!, drawingBox(LOOPS))
const CIRCLE = loopRef(LOOPS.find((l) => Math.abs(l.box.x1 - l.box.x0 - 16) < 0.5 && Math.abs(l.box.y1 - l.box.y0 - 16) < 0.5)!, drawingBox(LOOPS))
const lz: LaserWork = { material: 'PLYWOOD', file: 'Chains/a__logo.svg', ops: [{ id: 'a', kind: 'score', name: 'Mark', power: 0.2, feed: 1500, passes: 1, spacing: 0.2, angle: 0, loops: [SQUARE] }] }
const input = (c: Chain, b: Body[] = bodies) => ({
  chain: c, bodies: b, placed: place(b, { x: 150, y: 150 }),
  printJob: { ...newJob('BlockOne', 'fdm', [PLA]), engine: 'kiri' as const },
  laserJob: { ...newJob('LightSaber', 'laser', [{ key: 'PLYWOOD', name: 'PLYWOOD', laserPower: 0.6, feed: 600 }]), placement: { x: 150, y: 150, rotate: 0, scale: 1 } },
  laserSrc: new File(['x'], 'logo.svg'), laserMaterials: [{ key: 'PLYWOOD', name: 'PLYWOOD', laserPower: 0.6, feed: 600 }, { key: 'MYSTERY', name: 'MYSTERY' }], machine: DEFAULT_MACHINE, studioVersion: 'test',
})

describe('groupOf', () => {
  it('puts the bodies of one role where they sit on the bed, as one part', () => {
    const inp = input(chain())
    const g = groupOf(bodies, inp.placed, 'feature')!
    expect([g.x, g.y]).toEqual([150, 150])
    expect(g.part.size.x).toBeCloseTo(30)
    const f = groupOf(bodies, inp.placed, 'fixture')!
    expect(f.x).toBeCloseTo(93)
  })
  it('none of a role, none', () => expect(groupOf(bodies.slice(0, 1), place(bodies.slice(0, 1), { x: 1, y: 1 }), 'fixture')).toBeNull())
})

describe('building the print job', () => {
  it('stitches the fixtures, the pause, the raise and the features into one file that passes the check', async () => {
    calls.length = 0
    const [job1] = await buildJobs(input(chain({ laser: lz })), slicer)
    expect(job1!.problem).toBeNull()
    expect(job1!.file).toBe('front-plate-001_job1_print.gcode')
    const t = job1!.text!
    const at = (s: string) => t.indexOf(s)
    expect(at('START_JOB TOOLHEAD=BlockOne')).toBeGreaterThan(-1)
    expect(at(';RHINO_CHAIN fixtures')).toBeLessThan(at('PAUSE'))
    expect(at('PAUSE')).toBeLessThan(at('SET_GCODE_OFFSET Z_ADJUST=3 MOVE=0'))
    expect(at('SET_GCODE_OFFSET')).toBeLessThan(at(';RHINO_CHAIN features'))
    expect(t.trimEnd().endsWith('END_PRINT')).toBe(true)
    expect(calls.map((c) => c.x)).toEqual([93, 150])
    expect(job1!.checks.filter((c) => c.level === 'error')).toEqual([])
  })
  it('a print-only chain is one slice and no pause', async () => {
    const c = newChain('Bracket', 'print-laser', tools)
    const [j] = await buildJobs(input(c, [body(1, 'part', 'feature', 0, 0, 30, 20)]), slicer)
    expect(j!.text).not.toContain('PAUSE')
    expect(j!.text).not.toContain('SET_GCODE_OFFSET')
    expect(j!.problem).toBeNull()
  })
  it('says why when a group has no bodies or the sheet is not measured', async () => {
    const noFx = await buildJobs(input(chain(), bodies.filter((b) => b.role !== 'fixture')), slicer)
    expect(noFx[0]!.text).toBeNull()
    expect(noFx[0]!.problem).toMatch(/fixture/)
    const noT = await buildJobs(input(chain({ thickness: null })), slicer)
    expect(noT[0]!.problem).toMatch(/thickness/)
  })
})

describe('building the laser job', () => {
  // the stand-in cut's loops sit at X 127-143 (circle) and X 155-170 (square); a feature at X 145-152 is between them
  const between = [body(1, 'sheet', 'sheet', 0, 0, 100, 60, 3), body(2, 'jig', 'fixture', -12, 0, -2, 60, 4), body(3, 'bar', 'feature', 45, 20, 52, 40, 2)]
  const both: LaserWork = { ...lz, ops: [{ ...lz.ops[0]!, loops: [SQUARE, CIRCLE] }] }
  it('with features on the sheet: builds the laser file with lifts, the header, and passes the check', async () => {
    const jobs = await buildJobs(input(chain({ laser: both }), between), slicer)
    const j = jobs[1]!
    expect(j.problem).toBeNull()
    expect(j.lifts).toBeGreaterThanOrEqual(2)
    const t = j.text!
    expect(t).toContain('; rhino_chain_features = 2')
    expect(t).toContain('; rhino_chain_lift = 4')
    const lines = t.split('\n')
    expect(lines.filter((l) => l === 'G1 Z4 F600 ;RHINO_CHAIN lift').length).toBe(j.lifts)
    expect(lines.filter((l) => l === 'G1 Z0 F600 ;RHINO_CHAIN drop').length).toBe(j.lifts)
    expect(lines.some((l) => /^G[01]\b.*\bZ/.test(l) && !/RHINO_CHAIN (lift|drop)$/.test(l))).toBe(false)
    expect(j.checks.filter((c) => c.level === 'error')).toEqual([])
    expect(j.checks.find((c) => c.id === 'laserz')!.label).toMatch(/lift over the printed features/)
  })
  it('the tallest printed body sets the lift, a fixture counting by how far it stands above the sheet top', async () => {
    const tall = [body(1, 'sheet', 'sheet', 0, 0, 100, 60, 3), body(2, 'jig', 'fixture', -12, 0, -2, 60, 8), body(3, 'bar', 'feature', 45, 20, 52, 40, 2)]
    const j = (await buildJobs(input(chain({ laser: both }), tall), slicer))[1]!
    expect(j.text).toContain('; rhino_chain_features = 5')
    expect(j.text).toContain('; rhino_chain_lift = 7')
  })
  it('is refused when a picked loop lies over a printed feature, naming it', async () => {
    const j = (await buildJobs(input(chain({ laser: lz })), slicer))[1]!
    expect(j.text).toBeNull()
    expect(j.problem).toMatch(/lies over logo/)
  })
  it('a score around a feature is allowed (only its line matters), an engrave fill over it is not', async () => {
    const outline = loopRef(LOOPS.find((l) => l.box.x1 - l.box.x0 > 55)!, drawingBox(LOOPS))
    const around: LaserWork = { ...lz, ops: [{ ...lz.ops[0]!, loops: [outline] }] }
    const j = (await buildJobs(input(chain({ laser: around }), between), slicer))[1]!
    expect(j.problem).toBeNull()
    expect(j.lifts).toBeGreaterThanOrEqual(1)
    const fill: LaserWork = { ...lz, ops: [{ ...lz.ops[0]!, kind: 'fill', loops: [outline] }] }
    expect((await buildJobs(input(chain({ laser: fill }), between), slicer))[1]!.problem).toMatch(/lies over bar/)
  })
  it('is refused above the 20 mm a lift may clear', async () => {
    const huge = [body(1, 'sheet', 'sheet', 0, 0, 100, 60, 3), body(3, 'tower', 'feature', 45, 20, 52, 40, 25)]
    const c = chain({ laser: both })
    c.stages = c.stages.filter((s) => s.role !== 'fixtures')
    const j = (await buildJobs(input(c, huge), slicer)).at(-1)!
    expect(j.problem).toMatch(/more than the 20 mm/)
  })
  it('is built for a chain with nothing printed on the sheet: only the picked loop is lasered, no Z moves', async () => {
    const c = newChain('Marks', 'print-laser', tools)
    c.sheet = { width: 100, depth: 60, x: 150, y: 150 }
    c.stages = c.stages.filter((s) => s.kind === 'laser')
    c.laser = lz
    const jobs = await buildJobs(input(c, []), slicer)
    expect(jobs).toHaveLength(1)
    const j = jobs[0]!
    expect(j.problem).toBeNull()
    expect(j.file).toBe('marks_job1_laser.gcode')
    expect(j.text).toContain('; operation: Mark (score')
    expect(j.text).not.toContain('Everything else')
    expect(j.text!.split('\n').some((l) => /\bZ-?\d/.test(l) && /^G[01]/.test(l))).toBe(false)
    expect(j.text!.split('\n').filter((l) => l.startsWith('M3')).length).toBe(1)
  })
  it('no material, or one that is not in the head\'s table, means no laser file', async () => {
    const c = newChain('Marks', 'print-laser', tools)
    c.stages = c.stages.filter((s) => s.kind === 'laser')
    const none = (await buildJobs(input({ ...c, laser: { ...lz, material: undefined } }, []), slicer))[0]!
    expect(none.text).toBeNull()
    expect(none.problem).toMatch(/laser material is chosen/)
    const gone = (await buildJobs(input({ ...c, laser: { ...lz, material: 'GONE' } }, []), slicer))[0]!
    expect(gone.problem).toMatch(/isn.t in the laser head/)
    const noJob = (await buildJobs({ ...input({ ...c, laser: lz }, []), laserJob: null }, slicer))[0]!
    expect(noJob.problem).toMatch(/Pick the laser material/)
  })
  it('a material with no tested power builds with a note; the material and the checks are on the file', async () => {
    const c = newChain('Marks', 'print-laser', tools)
    c.stages = c.stages.filter((s) => s.kind === 'laser')
    const j = (await buildJobs(input({ ...c, laser: { ...lz, material: 'MYSTERY' } }, []), slicer))[0]!
    expect(j.problem).toBeNull()
    expect(j.checks.find((x) => x.id === 'laser-material')!.level).toBe('warn')
    const ok = (await buildJobs(input({ ...c, laser: lz }, []), slicer))[0]!
    expect(ok.checks.find((x) => x.id === 'laser-material')!.level).toBe('ok')
    expect(ok.text).toContain('; rhino_material = PLYWOOD')
  })
  it('a laser with no loops picked has nothing to do', async () => {
    const c = newChain('Marks', 'print-laser', tools)
    c.stages = c.stages.filter((s) => s.kind === 'laser')
    c.laser = { ...lz, ops: [{ ...lz.ops[0]!, loops: [] }] }
    const [j] = await buildJobs(input(c, []), slicer)
    expect(j!.text).toBeNull()
    expect(j!.problem).toMatch(/would do nothing/)
  })
  it('a slicer failure comes back as a reason, not a throw', async () => {
    const bad: Slicer = { ...slicer, fdm: async () => { throw new Error('Kiri:Moto made an empty file.') } }
    const [j] = await buildJobs(input(chain()), bad)
    expect(j!.problem).toBe('Kiri:Moto made an empty file.')
  })
})
